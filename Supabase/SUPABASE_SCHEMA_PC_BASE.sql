-- V85.35: Repair the identity sequence after legacy/manual notification rows.
-- This prevents PostgREST inserts from reusing an existing notifications.id.
DO $$
DECLARE
  seq_name text;
  max_id bigint;
BEGIN
  seq_name := pg_get_serial_sequence('public.notifications', 'id');
  IF seq_name IS NOT NULL THEN
    SELECT COALESCE(MAX(id), 0) INTO max_id FROM public.notifications;
    PERFORM setval(seq_name, max_id + 1, false);
  END IF;
END $$;

