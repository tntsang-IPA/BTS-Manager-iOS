create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  table_name text not null,
  row_pk text,
  action text not null,
  changed_at timestamptz not null default now(),
  changed_by uuid references auth.users(id) on delete set null,
  old_data jsonb,
  new_data jsonb
);

create index if not exists idx_audit_table_time on public.audit_log(table_name, changed_at desc);

create or replace function public.bts_set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.bts_audit_row()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  pk text;
begin
  if tg_op = 'DELETE' then
    pk := coalesce(to_jsonb(old)->>tg_argv[0], '');
    insert into public.audit_log(table_name,row_pk,action,changed_by,old_data)
    values (tg_table_name,pk,tg_op,auth.uid(),to_jsonb(old));
    return old;
  elsif tg_op = 'UPDATE' then
    pk := coalesce(to_jsonb(new)->>tg_argv[0], '');
    insert into public.audit_log(table_name,row_pk,action,changed_by,old_data,new_data)
    values (tg_table_name,pk,tg_op,auth.uid(),to_jsonb(old),to_jsonb(new));
    return new;
  else
    pk := coalesce(to_jsonb(new)->>tg_argv[0], '');
    insert into public.audit_log(table_name,row_pk,action,changed_by,new_data)
    values (tg_table_name,pk,tg_op,auth.uid(),to_jsonb(new));
    return new;
  end if;
end;
$$;

do $$
declare
  rec record;
begin
  for rec in
    select * from (values
      ('stations','code'),
      ('contracts','contract_id'),
      ('equipment','equipment_id'),
      ('transmission','transmission_id'),
      ('power','power_id'),
      ('batteries','battery_id'),
      ('auxiliary','aux_id'),
      ('maintenance','work_id'),
      ('mll_events','id'),
      ('mll_bsc_summary','id'),
      ('mll_analysis_summary','range_key'),
      ('kpi_targets','content')
    ) as x(table_name, pk_column)
  loop
    execute format('drop trigger if exists %I on public.%I', 'trg_'||rec.table_name||'_updated_at', rec.table_name);
    execute format('create trigger %I before update on public.%I for each row execute function public.bts_set_updated_at()', 'trg_'||rec.table_name||'_updated_at', rec.table_name);
    execute format('drop trigger if exists %I on public.%I', 'trg_'||rec.table_name||'_audit', rec.table_name);
    execute format('create trigger %I after insert or update or delete on public.%I for each row execute function public.bts_audit_row(%L)', 'trg_'||rec.table_name||'_audit', rec.table_name, rec.pk_column);
  end loop;
end $$;

-- Shared BTS Manager data: authenticated users can collaborate on the same dataset.
-- Anonymous/public requests are not allowed.
do $$
declare t text;
begin
  foreach t in array array['stations','contracts','equipment','transmission','power','batteries','auxiliary','maintenance','mll_events','mll_bsc_summary','mll_analysis_summary','kpi_targets'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "authenticated_select" on public.%I', t);
    execute format('drop policy if exists "authenticated_insert" on public.%I', t);
    execute format('drop policy if exists "authenticated_update" on public.%I', t);
    execute format('drop policy if exists "authenticated_delete" on public.%I', t);
    execute format('create policy "authenticated_select" on public.%I for select to authenticated using (true)', t);
    execute format('create policy "authenticated_insert" on public.%I for insert to authenticated with check (true)', t);
    execute format('create policy "authenticated_update" on public.%I for update to authenticated using (true) with check (true)', t);
    execute format('create policy "authenticated_delete" on public.%I for delete to authenticated using (true)', t);
  end loop;
end $$;

alter table public.audit_log enable row level security;
drop policy if exists "authenticated_audit_select" on public.audit_log;
